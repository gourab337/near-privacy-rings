// Emits circomlib Poseidon (t = 3) round constants and MDS matrix for contract/src/poseidon_consts.rs
// as ark-ff Montgomery-form limbs (R = 2^256 mod p), so the contract does no parsing at runtime.
import fs from 'node:fs';
import consts from '../sdk/node_modules/circomlibjs/src/poseidon_constants.js';
const P = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;
const R = (1n << 256n) % P;
const limbs = (x) => { const m = (BigInt(x) * R) % P; return `[${[0n, 1n, 2n, 3n].map((i) => '0x' + ((m >> (64n * i)) & 0xffffffffffffffffn).toString(16) + 'u64').join(', ')}]`; };
const T = 3, C = consts.C[T - 2], M = consts.M[T - 2];
const src = `// @generated by scripts/gen-poseidon.mjs from circomlibjs poseidon_constants (t = 3) — do not edit.
pub const N_ROUNDS_F: usize = 8;
pub const N_ROUNDS_P: usize = 57;
pub const C: [[u64; 4]; ${C.length}] = [\n${C.map((c) => '    ' + limbs(c) + ',').join('\n')}\n];
pub const M: [[[u64; 4]; 3]; 3] = [\n${M.map((row) => '    [' + row.map(limbs).join(', ') + '],').join('\n')}\n];
`;
fs.writeFileSync('contract/src/poseidon_consts.rs', src);
console.log('C', C.length, 'M', M.length);
