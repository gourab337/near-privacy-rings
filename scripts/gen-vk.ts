// Usage: node scripts/gen-vk.ts <vkey.json> <out.rs>
// Emits the Groth16 verifying key as NEAR alt_bn128 (little-endian) byte constants.
import fs from 'node:fs';
import { createHash } from 'node:crypto';
const [, , inPath, outPath] = process.argv;
const raw = fs.readFileSync(inPath);
const vk = JSON.parse(raw);
const sha = createHash('sha256').update(raw).digest('hex');
const le = (x) => [...Buffer.from(BigInt(x).toString(16).padStart(64, '0'), 'hex').reverse()];
const g1 = (p) => [...le(p[0]), ...le(p[1])];
const g2 = (p) => [...le(p[0][0]), ...le(p[0][1]), ...le(p[1][0]), ...le(p[1][1])];
const arr = (b) => `[${b.join(', ')}]`;
const src = `// @generated by scripts/gen-vk.ts from ${inPath.split('/').slice(-2).join('/')} — do not edit.
// vkey sha256: ${sha}
pub const N_PUBLIC: usize = ${vk.nPublic};
pub const ALPHA_G1: [u8; 64] = ${arr(g1(vk.vk_alpha_1))};
pub const BETA_G2: [u8; 128] = ${arr(g2(vk.vk_beta_2))};
pub const GAMMA_G2: [u8; 128] = ${arr(g2(vk.vk_gamma_2))};
pub const DELTA_G2: [u8; 128] = ${arr(g2(vk.vk_delta_2))};
pub const IC: [[u8; 64]; ${vk.IC.length}] = [
${vk.IC.map((p) => '    ' + arr(g1(p)) + ',').join('\n')}
];
`;
fs.writeFileSync(outPath, src);
console.log('wrote', outPath);
